/** 按码清单从主表挑键派生子表；缺码即抛错（防消费端引用未登记码，编译期之外的运行时哨兵）。 */
export function pickIpdCodeTexts(codes: readonly number[]): Record<number, string> {
  const out: Record<number, string> = {};
  for (const code of codes) {
    const text = IPD_CODE_TEXTS[code];
    if (text === undefined) {
      throw new Error(`IPD_CODE_TEXTS 缺少错误码 ${code} 的文案登记（R234 单一码表契约）`);
    }
    out[code] = text;
  }
  return out;
}
